const assert = require('node:assert/strict');
const test = require('node:test');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.join(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'tam', 'web', 'app.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'tam', 'web', 'index.src.html'), 'utf8');
const css = fs.readFileSync(path.join(root, 'tam', 'web', 'styles.css'), 'utf8');

const VIEWS = ['accounts', 'tasks', 'leads', 'toolbox', 'logs', 'settings'];

function viewHeadBlock() {
  const start = app.indexOf('const VIEWS =');
  assert.notEqual(start, -1, 'view-head module must declare its six view configurations');
  // The module is an IIFE appended as one unit.  Keep the static contract
  // scoped to that unit so existing data-view uses elsewhere remain valid.
  const end = app.indexOf('\n})();', start);
  return app.slice(start, end > start ? end : app.length);
}

test('view-head declares all six data-vh groups and never uses data-view', () => {
  const block = viewHeadBlock();
  for (const view of VIEWS) {
    assert.match(block, new RegExp(`(?:v|view)\\s*:\\s*['"]${view}['"]`), view);
  }
  assert.match(block, /dataset\.vh|data-vh/);
  assert.doesNotMatch(block, /data-view/);
  assert.match(block, /id\s*=\s*['"]viewHead['"]/);
  assert.match(block, /(?:before|insertBefore)\s*\(/, 'viewHead must precede #appShell');
});

test('view-head creates one title per group and synchronizes visibility via hidden', () => {
  const block = viewHeadBlock();
  // h1 is generated by the view-head builder rather than copied from cards.
  assert.match(block, /(?:createElement|el)\(\s*['"]h1['"]/);
  assert.match(block, /hidden\s*=|setAttribute\(\s*['"]hidden['"]|\[hidden\]/);
  assert.match(block, /querySelectorAll\([^)]*data-vh/);
  assert.match(block, /dataset\.vh\s*!==|dataset\.vh\s*===/);
  // Existing drawer/detail headings are not view-head titles.  The source
  // template must not accidentally claim a data-view title node.
  assert.doesNotMatch(html, /class=["'][^"']*vh-title[^"']*["'][^>]*data-view=/);
  assert.doesNotMatch(html, /data-view=["'][^"']*["'][^>]*class=["'][^"']*vh-title/);
});

test('view-head switches through applyView and keeps one fixed responsive height', () => {
  const block = viewHeadBlock();
  assert.match(block, /TAO_HOOK\.after\(\s*['"]applyView['"]/);
  assert.match(block, /(?:currentView|view)\b/);
  assert.match(css, /\.view-head\s*\{[^}]*--vh-h\s*:\s*76px/);
  assert.match(css, /@media\s*\(max-width\s*:\s*1000px\)[\s\S]*?\.view-head\s*\{[^}]*--vh-h\s*:\s*68px/);
  assert.match(css, /@media\s*\(max-width\s*:\s*720px\)[\s\S]*?\.view-head\s*\{[^}]*--vh-h\s*:\s*92px/);
  // A single custom property is the source of truth; changing the view must
  // only toggle hidden groups, never set per-view heights.
  assert.doesNotMatch(block, /(?:height|blockSize)\s*[:=][^;\n]*(?:accounts|tasks|leads|toolbox|logs|settings)/);
});

test('view-head action groups preserve existing nodes and delegated handlers', () => {
  const block = viewHeadBlock();
  assert.match(block, /append\s*\(/);
  assert.doesNotMatch(block, /cloneNode\s*\(|clone\s*\(/);
  assert.match(block, /vh-actions/);
  assert.match(block, /role["']?\s*[,=]\s*["']group["']/);
  for (const pattern of [
    /tools-right/, /add-btn/, /tao-one-stop/, /card:\s*['"]tasks['"]/,
    /card:\s*['"]leads['"]/, /data-widget=['"]toolbox['"]/, /#logPin/,
    /data-widget=['"]settings['"]/
  ]) assert.match(block, pattern, String(pattern));
});

test('view-head runtime keeps exactly one visible title while switching all views', () => {
  // Execute only the self-contained view-head IIFE against a deliberately
  // small DOM.  This catches a regression where a new group is appended but
  // the previous group is not hidden after applyView.
  const start = app.indexOf('/* ---------- 视图标题系统（view-head）');
  assert.notEqual(start, -1);
  const close = app.indexOf('\n})();', start);
  assert.ok(close > start);
  const source = app.slice(start, close + '\n})();'.length);
  assert.match(app, /createElement\(['"]p['"]\);\s*h\.className\s*=\s*['"]sr-only['"]/, 'screen-reader fallback must use the core sr-only utility');
  assert.doesNotMatch(app, /fx-sr/, 'the removed fx-sr utility must not remain in app.js');

  class Node {
    constructor(tag) {
      this.tagName = tag.toUpperCase(); this.children = []; this.parentNode = null;
      this.dataset = {}; this.className = ''; this.id = ''; this.hidden = false;
      this.attributes = {}; this.textContent = '';
    }
    append(...nodes) { nodes.forEach(node => this.appendChild(node)); }
    appendChild(node) { if (!node) return node; node.parentNode = this; this.children.push(node); return node; }
    before(node) {
      if (!this.parentNode) return;
      const list = this.parentNode.children, i = list.indexOf(this);
      node.parentNode = this.parentNode; list.splice(Math.max(i, 0), 0, node);
    }
    setAttribute(name, value) { this.attributes[name] = String(value); }
    _all() { return this.children.flatMap(child => [child, ...child._all()]); }
    querySelectorAll(selector) {
      const all = this._all();
      if (selector === '#viewHead [data-vh]' || selector === '[data-vh]') return all.filter(n => n.dataset && n.dataset.vh);
      if (selector === '.vh-title') return all.filter(n => n.className === 'vh-title');
      if (selector === 'h1') return all.filter(n => n.tagName === 'H1');
      if (selector === '.vh-copy:not([hidden])') return all.filter(n => n.className === 'vh-copy' && !n.hidden);
      return [];
    }
    querySelector(selector) { return this.querySelectorAll(selector)[0] || null; }
  }
  const body = new Node('body');
  const drawer = new Node('aside'); drawer.setAttribute('aria-hidden', 'true');
  drawer.appendChild(new Node('h1'));
  const shell = new Node('div'); shell.id = 'appShell'; body.append(drawer, shell);
  const document = {
    readyState: 'complete', body,
    createElement: tag => new Node(tag),
    getElementById(id) { return [body, ...body._all()].find(n => n.id === id) || null; },
    querySelector: () => null,
    querySelectorAll: selector => body.querySelectorAll(selector),
    addEventListener: () => {}
  };
  const hooks = [];
  const ctx = vm.createContext({
    document, window: {}, currentView: 'accounts', accounts: [], stats: {},
    TAO_HOOK: { after(name, fn) { if (name === 'applyView') hooks.push(fn); } },
    console
  });
  vm.runInContext(source, ctx);
  const head = document.getElementById('viewHead');
  assert.ok(head, '#viewHead should be inserted before #appShell');
  const groups = ['accounts', 'tasks', 'leads', 'toolbox', 'logs', 'settings'];
  for (const view of groups) {
    ctx.currentView = view;
    hooks.forEach(fn => fn());
    const visible = head.querySelectorAll('.vh-title').filter(title => !title.parentNode.hidden);
    assert.equal(visible.length, 1, `one visible h1 for ${view}`);
    assert.equal(visible[0].parentNode.dataset.vh, view);
    const documentH1 = body.querySelectorAll('h1').filter(h => {
      for (let node = h; node; node = node.parentNode) {
        if (node.hidden || node.attributes['aria-hidden'] === 'true') return false;
      }
      return true;
    });
    assert.equal(documentH1.length, 1, `one document-level h1 outside aria-hidden trees for ${view}`);
  }
});
